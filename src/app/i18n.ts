/** Every shipped key. Exported so tests can assert locale parity. */
export const TRANSLATION_KEYS: readonly TranslationKey[] = Object.freeze(
  Object.keys(en) as TranslationKey[],
);

export function resolveLocale(
  preference: LocalePreference,
  systemLocale = Intl.DateTimeFormat().resolvedOptions().locale,
): AppLocale {
  if (preference === "en" || preference === "zh-CN") return preference;
  return systemLocale.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function translate(
  locale: AppLocale,
  key: TranslationKey,
  values?: Readonly<Record<string, string | number>>,
): string {
  const copy = (locale === "zh-CN" ? zhCN : en)[key];
  if (!values) return copy;
  return copy.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = values[name];
    return value === undefined ? match : String(value);
  });
}
